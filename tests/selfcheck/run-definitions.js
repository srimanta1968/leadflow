/**
 * Local api_definition self-check runner.
 *
 * The ProjexLight review agent (`review-api-definitions`) currently scans the
 * MCP container's `/workspace`, which is mounted to a different project, so it
 * cannot verify LeadFlow's definitions. This runner is the stand-in: it reads
 * every file under tests/api_definitions/, resolves the placeholder vocabulary,
 * executes each testCase against a running server, and reports where the
 * definition and the handler disagree.
 *
 * It is deliberately a *verifier*, not a test framework — it proves the
 * definitions describe the real API, which is exactly the gate that is missing.
 *
 * Usage:  node tests/selfcheck/run-definitions.js [baseUrl]
 * Exit:   0 when every case matches its definition, 1 otherwise.
 */

const fs = require('fs');
const path = require('path');

const BASE_URL = process.argv[2] || 'http://localhost:3010';
const DEFS_DIR = path.join(__dirname, '..', 'api_definitions');
const CONFIG_PATH = path.join(__dirname, '..', 'config', 'test-config.json');

/** Values captured from earlier responses, keyed exactly as captureResponse declares. */
const cache = new Map();

/** User-defined variables from test-config.json. */
const variables = JSON.parse(fs.readFileSync(CONFIG_PATH, 'utf8')).variables || {};

const run = String(Date.now()).slice(-9);
let dynamicSeq = 0;

/** Generate a unique value for a {{dynamic:type}} placeholder. */
function dynamicValue(type) {
  dynamicSeq += 1;
  const unique = `${run}${dynamicSeq}`;
  switch (type) {
    case 'email':
      return `qa.${unique}@leadflow.test`;
    case 'username':
      return `qa_${unique}`;
    case 'password':
      return `LeadFlow!${unique}`;
    case 'name':
    case 'first_name':
    case 'last_name':
      return `QA ${unique}`;
    case 'company':
      return `Northwind ${unique}`;
    case 'phone':
      return `+1555${unique.slice(0, 7)}`;
    case 'text':
      return `Generated by the api_definition self-check, run ${unique}`;
    case 'uuid':
      return `00000000-0000-4000-8000-${unique.padStart(12, '0').slice(-12)}`;
    default:
      return `qa-${type}-${unique}`;
  }
}

/**
 * Resolve every placeholder form in a value.
 * @returns The resolved value, or a marker object when a cache key is missing.
 */
function resolve(value, missing) {
  if (typeof value === 'string') {
    return value.replace(/\{\{(\w+):([^}]+)\}\}/g, (_match, kind, arg) => {
      if (kind === 'dynamic') return dynamicValue(arg);
      if (kind === 'static') return arg;
      if (kind === 'var') {
        if (!(arg in variables)) missing.push(`{{var:${arg}}} not in test-config.json variables`);
        return variables[arg] ?? '';
      }
      if (kind === 'cache') {
        if (!cache.has(arg)) missing.push(`{{cache:${arg}}} was never captured`);
        return cache.get(arg) ?? '';
      }
      missing.push(`unknown placeholder form {{${kind}:...}}`);
      return '';
    });
  }
  if (Array.isArray(value)) return value.map((item) => resolve(item, missing));
  if (value && typeof value === 'object') {
    const out = {};
    for (const [key, inner] of Object.entries(value)) out[key] = resolve(inner, missing);
    return out;
  }
  return value;
}

/** Read a dotted path out of a response body. */
function readPath(body, dotted) {
  return dotted.split('.').reduce((acc, key) => (acc == null ? undefined : acc[key]), body);
}

/** Assert that `actual` contains every leaf of `expected`. */
function containsSubset(expected, actual, trail = '') {
  const problems = [];
  for (const [key, value] of Object.entries(expected)) {
    const here = trail ? `${trail}.${key}` : key;
    const got = actual == null ? undefined : actual[key];
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      problems.push(...containsSubset(value, got, here));
    } else if (got !== value) {
      problems.push(`${here}: expected ${JSON.stringify(value)}, got ${JSON.stringify(got)}`);
    }
  }
  return problems;
}

/** Collect every definition file, depth-first. */
function collect(dir) {
  const found = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) found.push(...collect(full));
    else if (entry.name.endsWith('.json')) found.push(full);
  }
  return found;
}

/** Order definitions so producers run before the tests that consume them. */
function byDependency(defs) {
  const key = (d) => `${d.def.method} ${d.def.endpoint}`;
  const done = new Set();
  const ordered = [];
  let remaining = [...defs];

  while (remaining.length) {
    const ready = remaining.filter((d) =>
      (d.def.dependsOn || []).every((dep) => done.has(dep))
    );
    // A cycle or an unresolvable dependency must not hang the runner; fall back
    // to declared priority so the remainder still executes and reports.
    const batch = ready.length
      ? ready
      : [...remaining].sort((a, b) => (a.def.priority ?? 999) - (b.def.priority ?? 999)).slice(0, 1);
    for (const d of batch) {
      ordered.push(d);
      done.add(key(d));
    }
    remaining = remaining.filter((d) => !batch.includes(d));
  }
  return ordered;
}

async function main() {
  const files = collect(DEFS_DIR);
  const defs = files.map((file) => ({
    file: path.relative(path.join(__dirname, '..', '..'), file).replace(/\\/g, '/'),
    def: JSON.parse(fs.readFileSync(file, 'utf8')),
  }));

  const ordered = byDependency(defs);
  let passed = 0;
  let failed = 0;
  const failures = [];

  for (const { file, def } of ordered) {
    console.log(`\n${def.method} ${def.endpoint}   (${file})`);

    for (const testCase of def.testCases || []) {
      const missing = [];
      const headers = { ...resolve(testCase.headers || {}, missing) };
      const payload =
        testCase.payload === undefined ? undefined : resolve(testCase.payload, missing);
      const pathParams = resolve(testCase.pathParams || {}, missing);
      const queryParams = resolve(testCase.queryParams || {}, missing);

      if (missing.length) {
        failed += 1;
        failures.push(`${file} :: ${testCase.name} :: ${missing.join('; ')}`);
        console.log(`  ✗ ${testCase.name}\n      ${missing.join('\n      ')}`);
        continue;
      }

      let url = def.endpoint;
      for (const [param, value] of Object.entries(pathParams)) {
        url = url.replace(`:${param}`, encodeURIComponent(value));
      }
      const query = new URLSearchParams(queryParams).toString();
      if (query) url += `?${query}`;

      if (payload !== undefined) headers['Content-Type'] = 'application/json';

      // A streaming endpoint holds the connection open, so reading its body to
      // completion would hang until the process is killed. Abort the read once
      // the headers arrive and assert the handshake only, which is exactly what
      // the definition documents (MUST-63).
      const controller = new AbortController();
      const response = await fetch(`${BASE_URL}${url}`, {
        method: def.method,
        headers,
        body: payload === undefined ? undefined : JSON.stringify(payload),
        signal: controller.signal,
      });

      const contentType = response.headers.get('content-type') ?? '';
      const isStream = contentType.includes('text/event-stream');

      let body = {};
      if (isStream) {
        controller.abort();
      } else {
        const text = await response.text();
        body = text ? JSON.parse(text) : {};
      }

      const problems = [];
      const wantStatus = testCase.expectedStatus ?? def.expectedStatus;
      if (response.status !== wantStatus) {
        problems.push(`status: expected ${wantStatus}, got ${response.status}`);
      }
      if (testCase.expectedResponse) {
        problems.push(...containsSubset(testCase.expectedResponse, body));
      }
      // A streaming definition asserts response HEADERS rather than a body,
      // because the body never ends.
      if (testCase.expectedHeaders) {
        for (const [header, expected] of Object.entries(testCase.expectedHeaders)) {
          const actual = response.headers.get(header) ?? '';
          if (!actual.includes(expected)) {
            problems.push(`header ${header}: expected to contain '${expected}', got '${actual}'`);
          }
        }
      }
      if (testCase.expectedError?.code && body.code !== testCase.expectedError.code) {
        problems.push(
          `error code: expected ${testCase.expectedError.code}, got ${JSON.stringify(body.code)}`
        );
      }

      // Only a passing happy-path case may seed the cache; capturing from a
      // failed response would propagate nulls into every downstream test.
      if (!problems.length && def.captureResponse && response.ok) {
        for (const [cacheKey, responsePath] of Object.entries(def.captureResponse)) {
          const captured = readPath(body, responsePath);
          if (captured === undefined) {
            problems.push(`captureResponse '${responsePath}' is absent from the response`);
          } else {
            cache.set(cacheKey, captured);
          }
        }
      }

      if (problems.length) {
        failed += 1;
        failures.push(`${file} :: ${testCase.name} :: ${problems.join('; ')}`);
        console.log(`  ✗ ${testCase.name}\n      ${problems.join('\n      ')}`);
      } else {
        passed += 1;
        console.log(`  ✓ ${testCase.name}  [${response.status}]`);
      }
    }
  }

  console.log(`\n${'='.repeat(64)}`);
  console.log(`definitions: ${defs.length}   cases passed: ${passed}   failed: ${failed}`);
  if (failures.length) {
    console.log('\nFAILURES');
    failures.forEach((f) => console.log(`  - ${f}`));
  }
  console.log('='.repeat(64));
  process.exit(failed === 0 ? 0 : 1);
}

main().catch((error) => {
  console.error('self-check runner failed:', error);
  process.exit(1);
});
